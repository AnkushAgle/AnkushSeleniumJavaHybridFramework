    private void generateSummaryTable(Writer writer, List<ISuite> suites) throws IOException {
        int totalPassed = 0, totalFailed = 0, totalSkipped = 0;
        long totalTime = 0;

        writer.write("<h2 class='section-title'><i class='fas fa-chart-bar'></i> Summary</h2>");

        for (ISuite suite : suites) {
            for (ISuiteResult result : suite.getResults().values()) {
                ITestContext context = result.getTestContext();
                totalPassed += context.getPassedTests().size();
                totalFailed += context.getFailedTests().size();
                totalSkipped += context.getSkippedTests().size();
                totalTime += context.getEndDate().getTime() - context.getStartDate().getTime();
            }
        }
        int totalMethods = totalPassed + totalFailed + totalSkipped;

        writer.write("<div class='summary-cards'>");
        writer.write(summaryCard("Passed", "passed", totalPassed, totalMethods));
        writer.write(summaryCard("Failed", "failed", totalFailed, totalMethods));
        writer.write(summaryCard("Skipped", "skipped", totalSkipped, totalMethods));
        writer.write("<div class='card duration'><div class='card-value'>" + formatDurationShort(totalTime) + "</div><div class='card-label'>Duration</div></div>");
        writer.write("</div>");
    }

    private String summaryCard(String label, String cls, int value, int total){
        return "<div class='card "+cls+"'><div class='card-value'>"+value+"</div><div class='card-label'>"+label+"</div><div class='card-percent'>"+PERCENTAGE.format(value/(double)total)+"</div></div>";
    }

    private void generateResultTables(Writer writer, List<ISuite> suites) throws IOException {
        writer.write("<h2 class='section-title'><i class='fas fa-table'></i> Test Results</h2>");
        writer.write("<div class='results-tabs'>");
        writer.write("<button class='tab-btn active' onclick=\"showTab('passed-tests')\">Passed</button>");
        writer.write("<button class='tab-btn' onclick=\"showTab('failed-tests')\">Failed</button>");
        writer.write("<button class='tab-btn' onclick=\"showTab('skipped-tests')\">Skipped</button>");
        writer.write("</div>");
        writer.write("<div id='passed-tests' class='tab-content active'>"); writeResultTable(writer,suites,"passed"); writer.write("</div>");
        writer.write("<div id='failed-tests' class='tab-content'>"); writeResultTable(writer,suites,"failed"); writer.write("</div>");
        writer.write("<div id='skipped-tests' class='tab-content'>"); writeResultTable(writer,suites,"skipped"); writer.write("</div>");
    }

    private void writeResultTable(Writer writer, List<ISuite> suites, String status) throws IOException {
        boolean hasResults = false;
        for(ISuite suite:suites){for(ISuiteResult result:suite.getResults().values()){IResultMap m=getResultMap(result.getTestContext(),status);if(!m.getAllResults().isEmpty()){hasResults=true;break;}}if(hasResults)break;}
        if(!hasResults){writer.write("<div class='no-results'>No "+status+" tests found</div>"); return;}
        writer.write("<table class='results-table "+status+"'><thead><tr><th>TestCaseId</th><th>Description</th><th>Status</th><th>Duration</th></tr></thead>");
        for(ISuite suite:suites){
            for(ISuiteResult result:suite.getResults().values()){
                ITestContext context=result.getTestContext();
                IResultMap rMap=getResultMap(context,status);
                List<ITestResult> results=new ArrayList<>(rMap.getAllResults());
                results.sort(Comparator.comparingLong(ITestResult::getStartMillis));
                for(ITestResult tr:results){
                    String uniqueId="m"+tr.getMethod().getMethodName()+"_"+tr.getStartMillis();
                    writer.write("<tr>");
                    writer.write("<td><a href='#"+uniqueId+"' class='method-link'>"+escapeHtml(tr.getMethod().getMethodName())+"</a></td>");
                    writer.write("<td>"+escapeHtml(tr.getMethod().getDescription()!=null?tr.getMethod().getDescription():"")+"</td>");
                    writer.write("<td><span class='status-badge "+status+"'>"+getStatus(tr.getStatus())+"</span></td>");
                    writer.write("<td>"+formatDuration(tr.getEndMillis()-tr.getStartMillis())+"</td>");
                    writer.write("</tr>");
                }
            }
        }
        writer.write("</table>");
    }

    private void generateDetailsContent(Writer writer, List<ISuite> suites) throws IOException {
        for(ISuite suite:suites){
            for(ISuiteResult result:suite.getResults().values()){
                ITestContext context=result.getTestContext();
                writeTestDetails(writer,context.getPassedTests(),"passed");
                writeTestDetails(writer,context.getFailedTests(),"failed");
                writeTestDetails(writer,context.getSkippedTests(),"skipped");
            }
        }
    }

    private void writeTestDetails(Writer writer, IResultMap results, String status) throws IOException {
        for(ITestResult tr:results.getAllResults()){
            String uniqueId="m"+tr.getMethod().getMethodName()+"_"+tr.getStartMillis();
            writer.write("<div id='"+uniqueId+"' class='test-detail "+status+"'>");
            writer.write("<div class='test-header'><h3>"+escapeHtml(tr.getMethod().getMethodName())+"</h3>");
            if(tr.getMethod().getDescription()!=null) writer.write("<span class='desc'>"+escapeHtml(tr.getMethod().getDescription())+"</span>");
            writer.write("<span class='status-badge "+status+"'>"+getStatus(tr.getStatus())+"</span></div>");
            writer.write("<div class='test-meta'><span><i class='far fa-clock'></i> "+formatDuration(tr.getEndMillis()-tr.getStartMillis())+"</span>");
            writer.write("<span><i class='far fa-calendar-alt'></i> "+formatDate(tr.getStartMillis())+"</span></div>");

            if(tr.getParameters()!=null && tr.getParameters().length>0){
                writer.write("<div class='test-section'><h4>Parameters</h4><div class='parameters'>");
                for(int i=0;i<tr.getParameters().length;i++){
                    writer.write("<div class='parameter'><span>Parameter "+(i+1)+":</span> "+escapeHtml(tr.getParameters()[i]!=null?tr.getParameters()[i].toString():"null")+"</div>");
                }
                writer.write("</div></div>");
            }

            List<String> output=Reporter.getOutput(tr);
            if(!output.isEmpty()){
                writer.write("<div class='test-section'><h4>Output</h4><div class='test-output'>");
                for(String line:output) writer.write("<div>"+line+"</div>");
                writer.write("</div></div>");
            }

            if(tr.getThrowable()!=null){
                writer.write("<div class='test-section'><h4>Exception</h4><div class='stack-trace'>");
                String[] lines=Utils.longStackTrace(tr.getThrowable(),true).split("\n");
                for(String line:lines) writer.write("<div>"+escapeHtml(line)+"</div>");
                writer.write("</div></div>");
            }

            writer.write("</div>");
        }
    }

    private IResultMap getResultMap(ITestContext context,String status){
        switch(status){
            case "failed": return context.getFailedTests();
            case "skipped": return context.getSkippedTests();
            default: return context.getPassedTests();
        }
    }

    private String getStatus(int status){
        switch(status){
            case ITestResult.SUCCESS: return "PASSED";
            case ITestResult.FAILURE: return "FAILED";
            case ITestResult.SKIP: return "SKIPPED";
            default: return "UNKNOWN";
        }
    }

    private String escapeHtml(String s){ if(s==null)return""; return s.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;").replace("\"","&quot;").replace("'","&#39;");}
    private String formatDate(long millis){ return new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date(millis)); }
    private String formatDuration(long millis){ long h=TimeUnit.MILLISECONDS.toHours(millis); millis-=TimeUnit.HOURS.toMillis(h); long m=TimeUnit.MILLISECONDS.toMinutes(millis); millis-=TimeUnit.MINUTES.toMillis(m); long s=TimeUnit.MILLISECONDS.toSeconds(millis); return String.format("%02d:%02d:%02d",h,m,s);}
    private String formatDurationShort(long millis){ long h=TimeUnit.MILLISECONDS.toHours(millis); millis-=TimeUnit.HOURS.toMillis(h); long m=TimeUnit.MILLISECONDS.toMinutes(millis); return String.format("%dh %02dm",h,m);}
    
